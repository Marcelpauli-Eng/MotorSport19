-- =====================================================================
-- V14 - Roles con permisos a la carta
-- =====================================================================
--
-- Hasta aqui los roles eran tres y estaban clavados en el codigo: ADMIN,
-- MOSTRADOR y TECNICO. Servia mientras el reparto de tareas fuera ese, pero en
-- cuanto un taller quiere «que Juan pueda dar de alta clientes pero no tocar el
-- almacen» no hay donde tocar.
--
-- Ahora el rol es una fila con su lista de permisos, y el administrador los
-- compone. El catalogo de permisos SI sigue en el codigo (enum Permiso): un
-- permiso que no se comprueba en ninguna parte seria una casilla que no protege
-- nada.
--
-- Los tres roles de siempre se crean aqui con exactamente los permisos que
-- tenian, de modo que despues de esta migracion nadie gana ni pierde nada.

-- ---------------------------------------------------------------------
-- Roles
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50)  NOT NULL,
    descripcion VARCHAR(200),
    -- Un rol de sistema no se puede borrar. ADMIN ademas no se puede editar:
    -- es el que reparte los permisos, y dejar que se quite el suyo propio es
    -- la forma mas rapida de quedarse fuera del programa para siempre.
    sistema     BOOLEAN      NOT NULL DEFAULT FALSE,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by  BIGINT,
    version     INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT uq_rol_nombre CHECK (length(trim(nombre)) > 0)
);

CREATE UNIQUE INDEX uq_rol_nombre_unico ON rol (upper(nombre));

COMMENT ON TABLE  rol         IS 'Roles del taller. Los compone el administrador a partir del catalogo de permisos.';
COMMENT ON COLUMN rol.sistema IS 'Rol de serie: no se borra. El de administrador tampoco se edita.';


-- ---------------------------------------------------------------------
-- Permisos de cada rol
-- ---------------------------------------------------------------------
CREATE TABLE rol_permiso (
    rol_id  BIGINT      NOT NULL,
    permiso VARCHAR(50) NOT NULL,

    CONSTRAINT pk_rol_permiso  PRIMARY KEY (rol_id, permiso),
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (rol_id) REFERENCES rol (id) ON DELETE CASCADE
);

COMMENT ON TABLE rol_permiso IS 'Permisos concedidos a un rol. El catalogo valido vive en el enum Permiso.';


