UPDATE usuario SET rol_id = CASE rol
    WHEN 'ADMIN'     THEN 1
    WHEN 'MOSTRADOR' THEN 2
    WHEN 'TECNICO'   THEN 3
END;

ALTER TABLE usuario ALTER COLUMN rol_id SET NOT NULL;
ALTER TABLE usuario ADD CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol (id);

-- El enum de texto ya no manda: se va, con su check y su indice.
DROP INDEX IF EXISTS ix_usuario_rol;
ALTER TABLE usuario DROP CONSTRAINT IF EXISTS ck_usuario_rol;
ALTER TABLE usuario DROP COLUMN rol;

CREATE INDEX ix_usuario_rol ON usuario (rol_id) WHERE activo;

COMMENT ON COLUMN usuario.rol_id IS 'Rol del usuario. Los permisos salen de rol_permiso.';
